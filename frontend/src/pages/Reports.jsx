// ── Department-specific PDF generator ──
const departmentColor = 'teal';
const departmentColorStyles = COLOR_STYLES[departmentColor] || COLOR_STYLES.blue;

async function generateDepartmentPdf(doc, data) {
  const { generatedBy, generatedAt, department, summary, items, lowStockItems, typeBreakdown, movement, budget, recentTransactions } = data;
  const { pw, dateStr } = addHeader(doc, `${department.name} INVENTORY REPORT`, generatedBy, generatedAt);
  let yPos = 60;

  // SECTION 1: Department Summary
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('1. DEPARTMENT SUMMARY', 14, yPos);

  autoTable(doc, {
    startY: yPos + 6,
    body: [
      ['Department', department.name],
      ['Total Items', String(summary.totalItems)],
      ['Total Stock Quantity', String(summary.totalStock)],
      ['Total Inventory Value', `${fmt(summary.totalValue)} RWF`],
      ['Categories', String(summary.totalCategories)],
      ['Low Stock Items', String(summary.lowStockCount)],
      ['Out of Stock Items', String(summary.outOfStockCount)],
    ],
    theme: 'grid',
    styles: { fontSize: 8.5, cellPadding: 3, overflow: 'linebreak' },
    columnStyles: { 0: { cellWidth: 50, fontStyle: 'bold' }, 1: { cellWidth: 50, halign: 'center' } },
    margin: { left: 5, right: 5 },
    tableWidth: 'auto',
  });
  yPos = doc.lastAutoTable.finalY + 12;

  // SECTION 2: Inventory Items
  if (yPos > 240) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('2. INVENTORY ITEMS', 14, yPos);
  yPos += 8;

  if (!items || items.length === 0) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text('No items found in this department.', 14, yPos);
    yPos += 12;
  } else {
    const itemRows = items.slice(0, 50).map(item => [
      String(item.sku || '-').substring(0, 15),
      String(item.name || '').substring(0, 35),
      String(item.category || '-').substring(0, 20),
      String(item.quantity),
      String(item.minimum_stock),
      item.unit_cost ? fmt(item.unit_cost) : '-',
      item.quantity === 0 ? 'OUT' : item.quantity <= item.minimum_stock ? 'LOW' : 'OK',
    ]);

    if (items.length > 50) itemRows.push(['...', `+${items.length - 50} more items`, '', '', '', '', '']);

    autoTable(doc, {
      startY: yPos,
      head: [['SKU', 'Name', 'Category', 'Qty', 'Min', 'Cost', 'Status']],
      body: itemRows,
      theme: 'grid',
      headStyles: { fillColor: [13, 148, 136], textColor: 255, fontStyle: 'bold', fontSize: 7, halign: 'center' },
      styles: { fontSize: 6.5, cellPadding: 1.5, overflow: 'linebreak' },
      columnStyles: {
        0: { cellWidth: 22 }, 1: { cellWidth: 50 }, 2: { cellWidth: 28 },
        3: { cellWidth: 14, halign: 'center' }, 4: { cellWidth: 14, halign: 'center' },
        5: { cellWidth: 22, halign: 'right' }, 6: { cellWidth: 16, halign: 'center' },
      },
      didParseCell: (cellData) => {
        if (cellData.section === 'body' && cellData.column.index === 6) {
          const s = cellData.cell.raw;
          if (s === 'OUT') Object.assign(cellData.cell.styles, { fillColor: [254, 202, 202], textColor: [153, 27, 27], fontStyle: 'bold' });
          else if (s === 'LOW') Object.assign(cellData.cell.styles, { fillColor: [254, 243, 199], textColor: [146, 64, 14], fontStyle: 'bold' });
          else Object.assign(cellData.cell.styles, { fillColor: [220, 252, 231], textColor: [22, 101, 52] });
        }
      },
      margin: { left: 5, right: 5 },
      tableWidth: 'auto',
    });
    yPos = doc.lastAutoTable.finalY + 10;
  }

  // SECTION 3: Low Stock Analysis
  if (yPos > 230) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('3. LOW STOCK ANALYSIS', 14, yPos);

  if (!lowStockItems || lowStockItems.length === 0) {
    yPos += 10;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text('No low stock items found.', 14, yPos);
    yPos += 12;
  } else {
    autoTable(doc, {
      startY: yPos + 6,
      head: [['Item', 'SKU', 'Qty', 'Min Stock', 'Category', 'Value']],
      body: lowStockItems.map(item => [
        String(item.name || '').substring(0, 35),
        String(item.sku || '-').substring(0, 15),
        String(item.quantity),
        String(item.minimum_stock),
        String(item.category || '-'),
        fmt(item.total_value),
      ]),
      theme: 'grid',
      headStyles: { fillColor: [245, 158, 11], textColor: 255, fontStyle: 'bold', fontSize: 8, halign: 'center' },
      styles: { fontSize: 7.5, cellPadding: 2, overflow: 'linebreak' },
      columnStyles: {
        0: { cellWidth: 50 }, 1: { cellWidth: 22 }, 2: { cellWidth: 16, halign: 'center' },
        3: { cellWidth: 22, halign: 'center' }, 4: { cellWidth: 22 }, 5: { cellWidth: 22, halign: 'right' },
      },
      didParseCell: (cellData) => {
        if (cellData.section === 'body' && cellData.column.index === 2) {
          Object.assign(cellData.cell.styles, { textColor: [220, 38, 38], fontStyle: 'bold' });
        }
      },
      margin: { left: 5, right: 5 },
      tableWidth: 'auto',
    });
    yPos = doc.lastAutoTable.finalY + 10;
  }

  // SECTION 4: Consumables vs Non-Consumables
  if (yPos > 230) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('4. ITEM TYPE BREAKDOWN', 14, yPos);

  if (typeBreakdown && typeBreakdown.length > 0) {
    autoTable(doc, {
      startY: yPos + 6,
      head: [['Type', 'Items', 'Total Qty', 'Total Value']],
      body: typeBreakdown.map(t => [
        String(t.item_type).charAt(0).toUpperCase() + String(t.item_type).slice(1),
        String(t.item_count),
        String(t.total_quantity),
        fmt(t.total_value),
      ]),
      theme: 'grid',
      headStyles: { fillColor: [37, 99, 235], textColor: 255, fontStyle: 'bold', fontSize: 8, halign: 'center' },
      styles: { fontSize: 8, cellPadding: 2.5, overflow: 'linebreak' },
      columnStyles: { 0: { cellWidth: 45 }, 1: { cellWidth: 20, halign: 'center' }, 2: { cellWidth: 25, halign: 'center' }, 3: { cellWidth: 35, halign: 'right' } },
      margin: { left: 5, right: 5 },
      tableWidth: 'auto',
    });
    yPos = doc.lastAutoTable.finalY + 10;
  } else {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text('No type breakdown data available.', 14, yPos + 10);
    yPos += 18;
  }

  // SECTION 5: Stock Movement Summary
  if (yPos > 230) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('5. STOCK MOVEMENT SUMMARY', 14, yPos);

  autoTable(doc, {
    startY: yPos + 6,
    body: [
      ['Stock In Transactions', String(movement.stock_in_count)],
      ['Stock In Quantity', String(movement.stock_in_qty)],
      ['Stock In Cost', `${fmt(movement.stock_in_cost)} RWF`],
      ['Stock Out Transactions', String(movement.stock_out_count)],
      ['Stock Out Quantity', String(movement.stock_out_qty)],
      ['Stock Out COGS', `${fmt(movement.stock_out_cogs)} RWF`],
    ],
    theme: 'grid',
    styles: { fontSize: 8.5, cellPadding: 3, overflow: 'linebreak' },
    columnStyles: { 0: { cellWidth: 55, fontStyle: 'bold' }, 1: { cellWidth: 40, halign: 'center' } },
    margin: { left: 5, right: 5 },
    tableWidth: 'auto',
  });
  yPos = doc.lastAutoTable.finalY + 10;

  // SECTION 6: Budget Utilization
  if (yPos > 230) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('6. BUDGET UTILIZATION', 14, yPos);

  if (budget && budget.total_budget > 0) {
    const remaining = Math.max(0, Number(budget.total_budget) - Number(budget.amount_used));
    const pct = budget.total_budget > 0 ? Math.round((budget.amount_used / budget.total_budget) * 100) : 0;

    autoTable(doc, {
      startY: yPos + 6,
      body: [
        ['Fiscal Year', String(budget.fiscal_year)],
        ['Total Budget', `${fmt(budget.total_budget)} RWF`],
        ['Amount Used', `${fmt(budget.amount_used)} RWF`],
        ['Remaining', `${fmt(remaining)} RWF`],
        ['Usage', `${pct}%`],
      ],
      theme: 'grid',
      styles: { fontSize: 8.5, cellPadding: 3, overflow: 'linebreak' },
      columnStyles: { 0: { cellWidth: 50, fontStyle: 'bold' }, 1: { cellWidth: 50, halign: 'center' } },
      didParseCell: (cellData) => {
        if (cellData.section === 'body' && cellData.column.index === 1) {
          const raw = cellData.cell.raw;
          if (typeof raw === 'string' && raw.includes('%')) {
            const pctVal = parseInt(raw);
            if (pctVal > 90) Object.assign(cellData.cell.styles, { textColor: [220, 38, 38], fontStyle: 'bold' });
            else if (pctVal > 70) Object.assign(cellData.cell.styles, { textColor: [245, 158, 11], fontStyle: 'bold' });
          }
        }
      },
      margin: { left: 5, right: 5 },
      tableWidth: 'auto',
    });
    yPos = doc.lastAutoTable.finalY + 10;
  } else {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text('No budget data available for this department.', 14, yPos + 10);
    yPos += 18;
  }

  // SECTION 7: Recent Transactions
  if (yPos > 230) { doc.addPage(); yPos = 20; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text('7. RECENT TRANSACTIONS', 14, yPos);

  if (recentTransactions && recentTransactions.length > 0) {
    autoTable(doc, {
      startY: yPos + 6,
      head: [['Date', 'Type', 'Item', 'Qty', 'Amount', 'By']],
      body: recentTransactions.map(t => [
        new Date(t.date).toLocaleDateString(),
        t.type,
        String(t.item_name || '').substring(0, 35),
        String(t.quantity),
        fmt(t.total_cost),
        String(t.user_name || '-').substring(0, 20),
      ]),
      theme: 'grid',
      headStyles: { fillColor: [13, 148, 136], textColor: 255, fontStyle: 'bold', fontSize: 8, halign: 'center' },
      styles: { fontSize: 7.5, cellPadding: 2, overflow: 'linebreak' },
      columnStyles: {
        0: { cellWidth: 22 }, 1: { cellWidth: 24, halign: 'center' }, 2: { cellWidth: 50 },
        3: { cellWidth: 14, halign: 'center' }, 4: { cellWidth: 22, halign: 'right' }, 5: { cellWidth: 22 },
      },
      didParseCell: (cellData) => {
        if (cellData.section === 'body' && cellData.column.index === 1) {
          if (cellData.cell.raw === 'Stock In') Object.assign(cellData.cell.styles, { textColor: [22, 163, 74], fontStyle: 'bold' });
          if (cellData.cell.raw === 'Stock Out') Object.assign(cellData.cell.styles, { textColor: [220, 38, 38], fontStyle: 'bold' });
        }
      },
      margin: { left: 5, right: 5 },
      tableWidth: 'auto',
    });
  } else {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(100);
    doc.text('No recent transactions for this department.', 14, yPos + 10);
  }

  addFooter(doc, pw, dateStr);
}

