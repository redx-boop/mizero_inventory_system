// ── PDF helpers ──────────────────────────────────
function addHeader(doc, title, generatedBy, generatedAt) {
  const pw = doc.internal.pageSize.getWidth();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('MIZERO INVENTORY HUB', pw / 2, 20, { align: 'center' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(14);
  doc.text(title, pw / 2, 28, { align: 'center' });
  doc.setFontSize(9);
  doc.setTextColor(80);
  const dateStr = new Date(generatedAt).toLocaleString();
  doc.text(`Generated By: ${generatedBy.full_name}`, 14, 38);
  doc.text(`Role: ${generatedBy.role}`, 14, 43);
  doc.text(`Date: ${dateStr}`, 14, 48);
  return { pw, dateStr };
}

function addFooter(doc, pw, dateStr) {
  const pageCount = doc.internal.getNumberOfPages();
  const pageH = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);

    // Signature block on the last page only
    if (i === pageCount) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(60);
      doc.text('Checked By: ________________________', 14, pageH - 28);
      doc.text('Approved By: ______________________', 14, pageH - 18);
      doc.setFontSize(8);
      doc.setTextColor(120);
      doc.text('(Signature)', 14, pageH - 23);
      doc.text('(Signature)', 14, pageH - 13);
    }

    // Page number
    doc.setFontSize(7);
    doc.setTextColor(150);
    doc.text(
      `Page ${i} of ${pageCount} — Mizero Inventory Hub — ${dateStr}`,
      pw / 2,
      pageH - 8,
      { align: 'center' }
    );
  }
}

function addSummaryTable(doc, label, rows, startY, columnWidths) {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(0);
  doc.text(label, 14, startY);

  autoTable(doc, {
    startY: startY + 6,
    body: rows,
    theme: 'grid',
    styles: { fontSize: 8, cellPadding: 3, overflow: 'linebreak' },
    columnStyles: columnWidths || { 0: { cellWidth: 55, fontStyle: 'bold' }, 1: { cellWidth: 40, halign: 'center' } },
    margin: { left: 5, right: 5 },
    tableWidth: 'auto',
  });
}

const fmt = (val) => {
  if (!val && val !== 0) return '0.00';
  return Number(val).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
};

// ── Format helper ──
const fmtShort = (val) => {
  if (!val && val !== 0) return '0';
  const num = Number(val);
  if (num >= 1000000) return (num / 1000000).toFixed(1) + 'M';
  if (num >= 1000) return (num / 1000).toFixed(1) + 'K';
  return String(num);
};

